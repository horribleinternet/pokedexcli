const LocationStartURL = "https://pokeapi.co/api/v2/location-area/"
const cachemsInterval = 5000
const pokemonURL = "https://pokeapi.co/api/v2/pokemon/"

var cache *pokecache.Cache

func init() {
	cache = pokecache.NewCache(cachemsInterval)
}

func LocationPokemon(area string) ([]string, error) {
	url := LocationStartURL + area + "/"
	bytes, err := getBuffer(url)
	if err != nil {
		return nil, err
	}
	var location locationArea
	if err := json.Unmarshal(bytes, &location); err != nil {
		return nil, err
	}
	pokemons := make([]string, len(location.PokemonEncounters))
	for i, encounter := range location.PokemonEncounters {
		pokemons[i] = encounter.Pokemon.Name
	}
	return pokemons, nil
}

